const MESSAGES: Record<Locale, Messages> = { en, he };
const INTL: Record<Locale, string> = { en: 'en-US', he: 'he-IL' };
const STORAGE_KEY = 'eee.locale';

/* =========================================================
   Formatting
   ========================================================= */

function parseIso(iso: string): Date {
  const [y, m, d] = iso.split('-').map(Number);
  return new Date(y, m - 1, d);
}

function formatters(locale: Locale) {
  const tag = INTL[locale];
  const dayMonth = new Intl.DateTimeFormat(tag, { month: 'short', day: 'numeric' });
  const dayMonthYear = new Intl.DateTimeFormat(tag, { month: 'short', day: 'numeric', year: 'numeric' });
  const pct = new Intl.NumberFormat(tag, { style: 'percent', maximumFractionDigits: 0 });
  const deadlineFmt = new Intl.DateTimeFormat(tag, { weekday: 'short', month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit', hourCycle: 'h23' });
  return {
    /** "Nov 15 – 21" / "15–21 בנוב׳", with the year when it isn't the current one. */
    weekRange(startIso: string, { year = false } = {}) {
      const start = parseIso(startIso);
      const end = new Date(start);
      end.setDate(end.getDate() + 6);
      const fmt = year || end.getFullYear() !== new Date().getFullYear() ? dayMonthYear : dayMonth;
      return fmt.formatRange(start, end);
    },
    shortDate: (iso: string) => dayMonth.format(parseIso(iso)),
    percent: (v: number | null) => (v == null ? '—' : pct.format(v)),
    /** "Sat, Nov 21, 23:59" / "שבת, 21 בנוב׳, 23:59" */
    deadline: (iso: string) => deadlineFmt.format(new Date(iso)),
    /** Rough time remaining: "2 days", "5 hours", "20 minutes" (Hebrew uses the dual forms). */
    duration(ms: number) {
      const minutes = Math.max(1, Math.round(ms / 60_000));
      const hours = Math.floor(minutes / 60);
      const days = Math.floor(hours / 24);
      if (locale === 'he') {
        if (days >= 1) return days === 1 ? 'יום אחד' : days === 2 ? 'יומיים' : `${days} ימים`;
        if (hours >= 1) return hours === 1 ? 'שעה' : hours === 2 ? 'שעתיים' : `${hours} שעות`;
        return minutes === 1 ? 'דקה' : `${minutes} דקות`;
      }
      if (days >= 1) return days === 1 ? '1 day' : `${days} days`;
      if (hours >= 1) return hours === 1 ? '1 hour' : `${hours} hours`;
      return minutes === 1 ? '1 minute' : `${minutes} minutes`;
    },
  };
}

/* =========================================================
   Context
   ========================================================= */

interface I18n {
  locale: Locale;
  dir: 'ltr' | 'rtl';
  t: Messages;
  fmt: ReturnType<typeof formatters>;
  setLocale: (l: Locale) => void;
  /** Translate an API error, falling back to its English text. */
  errorText: (e: unknown) => string;
}

const I18nContext = createContext<I18n | null>(null);

function initialLocale(): Locale {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'en' || saved === 'he') return saved;
  } catch {
    // storage unavailable
  }
  return navigator.languages?.some((l) => l.toLowerCase().startsWith('he') || l.toLowerCase().startsWith('iw')) ? 'he' : 'en';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(initialLocale);

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      // storage unavailable: the account preference still applies after sign-in
    }
  }, []);

  const value = useMemo<I18n>(() => {
    const t = MESSAGES[locale];
    return {
      locale,
      dir: locale === 'he' ? 'rtl' : 'ltr',
      t,
      fmt: formatters(locale),
      setLocale,
      errorText: (e: unknown) => {
        const code = (e as { code?: string })?.code;
        if (code && code in t.errors) return t.errors[code as ErrorCode];
        return (e as Error)?.message || t.errors.server_error;
      },
    };
  }, [locale, setLocale]);

  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = value.dir;
    document.title = value.t.appName;
  }, [locale, value]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18n {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n outside I18nProvider');
  return ctx;
}
